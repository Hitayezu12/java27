    private void registrerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registrerActionPerformed
        // TODO add your handling code here:
        
        
        String name = fullname.getText();
        String mail = email.getText();
        String user = username.getText();
        String pass = password.getText();
        String conf_pass = conf_password.getText();

        try {
            Connection con = DBConnection.connect();
            PreparedStatement pst = con.prepareStatement(
                "INSERT INTO users(fullname, username, password) VALUES (?, ?, ?)"
            );

            pst.setString(1, name);
            pst.setString(2, mail);
            pst.setString(3, user);
            pst.setString(4, pass);
            pst.setString(5, conf_pass);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "User Registered Successfully");

            Login_form lf = new Login_form();
            lf.setVisible(true);
            this.dispose();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
            System.out.println(e);
        }
        
        
        
    }//GEN-LAST:event_registrerActionPerformed

